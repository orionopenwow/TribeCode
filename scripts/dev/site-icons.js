#!/usr/bin/env node
// The website's app mocks use the app's own line icons (app/ui/icons.js), so the site and the app never drift.
// Writes site/app-icons.css: one CSS mask per mock icon (.mk-ic--<name>), drawn in currentColor like the app.
//   node scripts/dev/site-icons.js           write site/app-icons.css
//   node scripts/dev/site-icons.js --check   exit 1 when site/app-icons.css is out of date (npm test runs this)
'use strict';
const fs = require('fs'), path = require('path'), vm = require('vm');
const ROOT = path.resolve(__dirname, '..', '..');
const OUT = path.join(ROOT, 'site', 'app-icons.css');

// mock icon name on the site -> icon name in the app
const MAP = {
  home: 'home', chat: 'chat', file: 'files', grid: 'design', check: 'tasks', bot: 'agent', board: 'whiteboard',
  play: 'preview', people: 'people', bell: 'bell', gear: 'gear', plus: 'plus', search: 'search', help: 'book',
  store: 'store', company: 'company', monitor: 'monitor', phone: 'phone', link: 'link', sites: 'sites', spark: 'spark',
};

function paths() {
  const sandbox = { window: {}, document: undefined };
  vm.runInNewContext(fs.readFileSync(path.join(ROOT, 'app', 'ui', 'icons.js'), 'utf8'), sandbox);
  return sandbox.window.TribeIcons.paths;
}

function build() {
  const P = paths();
  const rules = Object.entries(MAP).map(([k, v]) => {
    if (!P[v]) throw new Error(`app icon "${v}" (for .mk-ic--${k}) is not in app/ui/icons.js`);
    const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" stroke="#000" stroke-width="1.9" stroke-linecap="round" stroke-linejoin="round">${P[v]}</svg>`;
    const uri = 'data:image/svg+xml,' + encodeURIComponent(svg).replace(/'/g, '%27');
    return `.mk-ic--${k} { --mk-ic: url("${uri}"); }`;
  });
  return `/* Generated by scripts/dev/site-icons.js from app/ui/icons.js: the app's line icons for the website's app mocks.
   Do not edit by hand; run the script after changing an icon in the app. */
.mk-ic { width: 15px; height: 15px; flex: none; border: 0 !important; border-radius: 0 !important; clip-path: none !important; opacity: .9;
  background: currentColor !important; -webkit-mask: var(--mk-ic) center / contain no-repeat; mask: var(--mk-ic) center / contain no-repeat; }
${rules.join('\n')}
`;
}

const css = build();
if (process.argv.includes('--check')) {
  const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  if (cur !== css) { console.error('site/app-icons.css is out of date: run node scripts/dev/site-icons.js'); process.exit(1); }
  console.log('site/app-icons.css matches app/ui/icons.js');
} else {
  fs.writeFileSync(OUT, css);
  console.log('wrote site/app-icons.css (' + Object.keys(MAP).length + ' icons)');
}
