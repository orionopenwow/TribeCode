#!/usr/bin/env node
// The website's Learn page (site/learn.html) shows the same quick guides the app does (templates/quickguides.json),
// so the site, the app and Flint never drift. This writes the part the page needs: the groups and, for each card, its
// title, the one-line why and the steps, with {tokens} filled from the file's own label text. Nothing is added here.
//   node scripts/dev/site-quick.js           write site/quick-guides.json
//   node scripts/dev/site-quick.js --check   exit 1 when site/quick-guides.json is out of date (npm test runs this)
'use strict';
const fs = require('fs'), path = require('path');
const ROOT = path.resolve(__dirname, '..', '..');
const OUT = path.join(ROOT, 'site', 'quick-guides.json');

function build() {
  const src = JSON.parse(fs.readFileSync(path.join(ROOT, 'templates', 'quickguides.json'), 'utf8'));
  const labels = src.labels || {}, fill = s => String(s).replace(/\{([a-z]+)\}/g, (m, k) => (labels[k] ? labels[k].text : k));
  const ids = new Set();
  const guides = (src.guides || []).map(g => {
    if (!g.id || ids.has(g.id)) throw new Error(`quick guide id missing or repeated: ${g.id}`); ids.add(g.id);
    if (!Array.isArray(g.steps) || g.steps.length < 3 || g.steps.length > 5) throw new Error(`"${g.id}" needs 3 to 5 steps`);
    return { id: g.id, group: g.group, title: g.title, intro: g.intro || '', asks: g.asks || [], steps: g.steps.map(fill) };
  });
  return JSON.stringify({ about: 'Generated by scripts/dev/site-quick.js from templates/quickguides.json. Do not edit by hand.', groups: src.groups || [], guides }, null, 1) + '\n';
}

const next = build();
if (process.argv.includes('--check')) {
  const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  if (cur !== next) { console.error('site/quick-guides.json is out of date: run node scripts/dev/site-quick.js'); process.exit(1); }
  console.log('site/quick-guides.json matches templates/quickguides.json');
} else { fs.writeFileSync(OUT, next); console.log('wrote site/quick-guides.json'); }
