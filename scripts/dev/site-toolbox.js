#!/usr/bin/env node
// The website's "free toolbox" page (site/toolbox.html) shows the same tools the app's Workshop › Studios lists
// (templates/studios.json), so the site and the app never drift. Name, one-line summary, licence, platforms and link
// come from the app's list; this file only adds what the page needs on top: three features and the kind of paid
// software each tool stands in for (a kind of tool, never a product name), which drawn card to show, and the real
// screenshot with its credit for the tools that have one (templates/studio-shots.json).
//   node scripts/dev/site-toolbox.js           write site/toolbox-data.json
//   node scripts/dev/site-toolbox.js --check   exit 1 when site/toolbox-data.json is out of date (npm test runs this)
// Licences and source links were read from each project's own licence file on 2026-11-13 (site/assets/toolbox/CREDITS.md).
'use strict';
const fs = require('fs'), path = require('path');
const ROOT = path.resolve(__dirname, '..', '..');
const OUT = path.join(ROOT, 'site', 'toolbox-data.json');
// Real screenshots, only where a project's terms clearly allow reuse (templates/studio-shots.json). The page shows the
// picture with its credit; the full record per picture also goes to site/assets/toolbox/credits.json.
const SHOTS = JSON.parse(fs.readFileSync(path.join(ROOT, 'templates', 'studio-shots.json'), 'utf8')).shots || {};
const CREDITS = path.join(ROOT, 'site', 'assets', 'toolbox', 'credits.json');
const shotFor = id => { const r = SHOTS[id]; return r ? { file: r.file, w: r.w, h: r.h, alt: r.alt, by: r.by, license: r.license, licenseUrl: r.licenseUrl, source: r.source } : null; };
function credits() {
  const images = Object.keys(SHOTS).map(id => { const r = SHOTS[id]; return { tool: id, files: [640, r.w].flatMap(w => [`${r.file}-${w}.webp`, `${r.file}-${w}.jpg`]), sourceUrl: r.source, originalFile: r.original, author: r.by, licence: r.license, licenceUrl: r.licenseUrl, terms: r.terms, date: r.fetched, changes: r.changes,
    attribution: `Screenshot: ${r.by}, ${r.license} (${r.licenseUrl}). Source: ${r.source}. ${r.changes}` }; });
  return JSON.stringify({ about: 'Generated by scripts/dev/site-toolbox.js from templates/studio-shots.json. Do not edit by hand. Every other picture on the toolbox page is an original TribeCode drawing.', images }, null, 1) + '\n';
}

// id in templates/studios.json -> what the page adds. The order here is the order on the page; the first is the feature.
const PAGE = [
  ['artcraft', {
    kind: 'AI image and video studio', art: 'artcraft', source: 'https://github.com/storytold/artcraft',
    features: ['Compose in 2D with layers, masks and cut-outs', 'Stage a scene in 3D before you generate it', 'Turn a still image into a short video'],
    more: ['Pose characters and set the camera first', 'Pick the image and video models you want', 'Export PNG, WebP and MP4 into your project'],
  }],
  ['blender', {
    kind: '3D modelling and animation suite', art: 'cube', source: 'https://github.com/blender/blender',
    features: ['Model, sculpt and texture', 'Rig and animate characters', 'Export glTF for three.js and Godot'],
  }],
  ['krita', {
    kind: 'Digital painting app', art: 'brush', source: 'https://github.com/KDE/krita',
    features: ['Brushes made for painting', 'Layers, masks and filters', 'Frame-by-frame animation'],
  }],
  ['godot', {
    kind: 'Game engine', art: 'play', source: 'https://github.com/godotengine/godot',
    features: ['2D and 3D in one editor', 'Export to desktop, phones and the web', 'No royalties, ever'],
  }],
  ['kdenlive', {
    kind: 'Video editor', art: 'timeline', source: 'https://github.com/KDE/kdenlive',
    features: ['As many video and audio tracks as you need', 'Titles, transitions and effects', 'Works with almost any video file'],
  }],
  ['audacity', {
    kind: 'Audio editor', art: 'wave', source: 'https://github.com/audacity/audacity',
    features: ['Record from a microphone', 'Cut, clean and level sound', 'Export WAV, MP3 and OGG'],
  }],
  ['penpot', {
    kind: 'Interface design tool', art: 'frames', source: 'https://github.com/penpot/penpot',
    features: ['Design screens in the browser', 'Components and prototypes', 'Inspect the CSS behind a design'],
  }],
  ['pixelorama', {
    kind: 'Pixel art editor', art: 'pixels', source: 'https://github.com/Orama-Interactive/Pixelorama',
    features: ['Sprites, tiles and animations', 'Onion skinning and layers', 'Export sprite sheets'],
  }],
  ['obs', {
    kind: 'Screen recorder and streaming app', art: 'record', source: 'https://github.com/obsproject/obs-studio',
    features: ['Record your screen and camera', 'Mix scenes and sources live', 'Stream to any platform'],
  }],
];

function build() {
  const src = JSON.parse(fs.readFileSync(path.join(ROOT, 'templates', 'studios.json'), 'utf8'));
  const tools = PAGE.map(([id, extra]) => {
    const s = (src.studios || []).find(x => x.id === id);
    if (!s) throw new Error(`"${id}" is not in templates/studios.json (the app's Studios list)`);
    const shot = shotFor(id);
    return Object.assign({ id, name: s.title, what: s.what, license: s.license, platforms: s.platforms, url: s.url, color: s.color }, extra, shot ? { shot } : {});
  });
  return JSON.stringify({ about: 'Generated by scripts/dev/site-toolbox.js from templates/studios.json. Do not edit by hand.', tools }, null, 1) + '\n';
}

const next = build(), nextCredits = credits();
if (process.argv.includes('--check')) {
  const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  const curC = fs.existsSync(CREDITS) ? fs.readFileSync(CREDITS, 'utf8') : '';
  if (curC !== nextCredits) { console.error('site/assets/toolbox/credits.json is out of date: run node scripts/dev/site-toolbox.js'); process.exit(1); }
  if (cur !== next) { console.error('site/toolbox-data.json is out of date: run node scripts/dev/site-toolbox.js'); process.exit(1); }
  console.log('site/toolbox-data.json matches templates/studios.json');
} else { fs.writeFileSync(OUT, next); fs.writeFileSync(CREDITS, nextCredits); console.log('wrote site/toolbox-data.json and site/assets/toolbox/credits.json'); }
