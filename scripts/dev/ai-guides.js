#!/usr/bin/env node
// The master guides for AI agents (docs/ai/*.md): fills their generated parts from the app's own data and writes the
// copy the server and the app serve (app/ui/aiguides-data.js).
//   node scripts/dev/ai-guides.js          write
//   node scripts/dev/ai-guides.js --check  exit 1 when a guide or the served copy is out of date (in npm test)
// A generated part sits between <!-- gen:<kind>:<part> --> and <!-- /gen --> in a guide. The words outside those marks
// are written by hand. The catalogues (sections, layouts, parts, looks, fonts, kits, templates) come from
// app/ui/sitecfg.js, appcreator-core.js and motionsocial.js; the steps and the design rules from app/ui/aiguide-core.js.
'use strict';
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..', '..');
const G = require(path.join(root, 'app/ui/aiguide-core.js'));
const LIB = { site: require(path.join(root, 'app/ui/sitecfg.js')), app: require(path.join(root, 'app/ui/appcreator-core.js')), motion: require(path.join(root, 'app/ui/motionsocial.js')) };
const FILES = { README: 'README.md', WEBSITE: 'WEBSITE.md', APP: 'APP.md', MOTION: 'MOTION.md' };
const MAX_LINES = 400;
const check = process.argv.includes('--check');
const RX = /(<!-- gen:(site|app|motion):([a-z]+) -->)\n[\s\S]*?(<!-- \/gen -->)/g;

function fill(text) {
  return text.replace(RX, (m, open, kind, part, close) => {
    const body = G.catalogMd(kind, LIB[kind], part);
    if (!body) throw new Error(`nothing to generate for ${kind}:${part}`);
    return `${open}\n${body}\n${close}`;
  });
}
let bad = 0; const out = {};
for (const [key, f] of Object.entries(FILES)) {
  const file = path.join(root, 'docs', 'ai', f), was = fs.readFileSync(file, 'utf8'), now = fill(was);
  const lines = now.split('\n').length;
  if (lines > MAX_LINES) { console.error(`ai-guides: docs/ai/${f} is ${lines} lines (the limit is ${MAX_LINES})`); bad++; }
  if (now !== was) { if (check) { console.error(`ai-guides: docs/ai/${f} is out of date: run node scripts/dev/ai-guides.js`); bad++; } else fs.writeFileSync(file, now); }
  out[key] = now;
}
// the recipes can only name sections, layouts and parts that exist
for (const r of G.RULES.site.recipes) for (const [t, v] of r.blocks) if (!LIB.site.BLOCKS[t] || !LIB.site.BLOCKS[t].variants.includes(v)) { console.error(`ai-guides: the recipe "${r.kind}" names ${t} · ${v}, which is gone`); bad++; }
for (const r of G.RULES.app.recipes) for (const [t] of r.blocks) if (!LIB.app.BLOCKS[t]) { console.error(`ai-guides: the recipe "${r.kind}" names the part ${t}, which is gone`); bad++; }

const data = `// Generated by scripts/dev/ai-guides.js from docs/ai/*.md. Do not edit: change the guide, then run the script.\n// The master guides for AI agents, as the server serves them (get_guide, .tribe/ai/ in a project folder).\n(function (root, api) { if (typeof module === 'object' && module.exports) module.exports = api; else root.TribeAIGuides = api; })(typeof self !== 'undefined' ? self : this, ${JSON.stringify(out, null, 0)});\n`;
const dfile = path.join(root, 'app', 'ui', 'aiguides-data.js');
const dwas = fs.existsSync(dfile) ? fs.readFileSync(dfile, 'utf8') : '';
if (data !== dwas) { if (check) { console.error('ai-guides: app/ui/aiguides-data.js is out of date: run node scripts/dev/ai-guides.js'); bad++; } else fs.writeFileSync(dfile, data); }
if (bad) process.exit(1);
console.log(`ai-guides: ${check ? 'up to date' : 'written'} (${Object.entries(out).map(([k, t]) => `${FILES[k]} ${t.split('\n').length} lines`).join(', ')})`);
